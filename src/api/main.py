"""
Step 8a: FastAPI backend serving the crop yield prediction dashboard.

Three endpoints map directly onto the three dashboard query patterns
load_database.py's schema was indexed for:
  - /predictions/map           -> choropleth (all counties, one year+commodity)
  - /predictions/county/{fips} -> one county's full history (trend line)
  - /anomalies                 -> flagged counties sorted by anomaly score

/commodities and /years exist purely to populate dropdown options without
hardcoding them in the frontend — if the underlying data ever changes
(a new commodity added, a new year ingested), the dashboard reflects it
automatically rather than needing a matching frontend code change.

Run locally: uvicorn src.api.main:app --reload --port 8000
Interactive docs (auto-generated by FastAPI): http://localhost:8000/docs
"""

from typing import List

from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from sqlalchemy import text

from .database import engine
from .schemas import AnomalyRecord, CountyPrediction, CountyTrendPoint

app = FastAPI(title="Crop Yield Prediction API")

# Dashboard runs on a different port (8050) locally, so the browser
# treats it as a different origin — CORS must be permissive for the
# dashboard's browser-side requests to succeed. Tighten allow_origins
# to the actual deployed dashboard URL in Step 9 rather than leaving
# this wide open in production.
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_methods=["GET"],
    allow_headers=["*"],
)


@app.get("/health")
def health():
    return {"status": "ok"}


@app.get("/commodities", response_model=List[str])
def get_commodities():
    with engine.connect() as conn:
        rows = conn.execute(text("SELECT DISTINCT commodity FROM predictions ORDER BY commodity")).fetchall()
    return [r[0] for r in rows]


@app.get("/years", response_model=List[int])
def get_years(commodity: str = Query(...)):
    with engine.connect() as conn:
        rows = conn.execute(
            text("SELECT DISTINCT year FROM predictions WHERE commodity = :commodity ORDER BY year"),
            {"commodity": commodity},
        ).fetchall()
    if not rows:
        raise HTTPException(status_code=404, detail=f"No data for commodity '{commodity}'")
    return [r[0] for r in rows]


@app.get("/predictions/map", response_model=List[CountyPrediction])
def get_map_predictions(year: int, commodity: str):
    query = text("""
        SELECT county_fips, county_name, state_alpha, year, commodity,
               lgbm_pred, prophet_pred, ensemble_pred, actual,
               is_anomaly, anomaly_score, model_disagreement, prophet_available
        FROM predictions
        WHERE year = :year AND commodity = :commodity
    """)
    with engine.connect() as conn:
        rows = conn.execute(query, {"year": year, "commodity": commodity}).mappings().all()
    if not rows:
        raise HTTPException(status_code=404, detail=f"No predictions for {commodity} {year}")
    return [dict(r) for r in rows]


@app.get("/predictions/county/{county_fips}", response_model=List[CountyTrendPoint])
def get_county_trend(county_fips: str, commodity: str = Query(...)):
    query = text("""
        SELECT year, lgbm_pred, prophet_pred, ensemble_pred, actual, is_anomaly
        FROM predictions
        WHERE county_fips = :county_fips AND commodity = :commodity
        ORDER BY year
    """)
    with engine.connect() as conn:
        rows = conn.execute(query, {"county_fips": county_fips, "commodity": commodity}).mappings().all()
    if not rows:
        raise HTTPException(status_code=404, detail=f"No data for county {county_fips}, {commodity}")
    return [dict(r) for r in rows]


@app.get("/anomalies", response_model=List[AnomalyRecord])
def get_anomalies(year: int, commodity: str, limit: int = 25):
    query = text("""
        SELECT county_fips, county_name, state_alpha, year, commodity,
               ensemble_pred, actual, anomaly_score, model_disagreement
        FROM predictions
        WHERE year = :year AND commodity = :commodity AND is_anomaly = true
        ORDER BY anomaly_score DESC
        LIMIT :limit
    """)
    with engine.connect() as conn:
        rows = conn.execute(query, {"year": year, "commodity": commodity, "limit": limit}).mappings().all()
    return [dict(r) for r in rows]